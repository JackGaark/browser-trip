import { createSound, initSoundButton } from "./core/sound.js";
import { initProgress } from "./core/progress.js";
import { initUrl } from "./scenes/url.js";
import { initDns } from "./scenes/dns.js";
import { initHandshake } from "./scenes/handshake.js";
import { initHttp } from "./scenes/http.js";
import { initDom } from "./scenes/dom.js";
import { initScripts } from "./scenes/scripts.js";
import { initLayout } from "./scenes/layout.js";
import { initPaint } from "./scenes/paint.js";
import { initLayers } from "./scenes/layers.js";
import { initRaster } from "./scenes/raster.js";
import { initV8 } from "./scenes/v8.js";
import { initGarbageCollection } from "./scenes/garbage-collection.js";
import { initProcesses } from "./scenes/processes.js";
import { initOutro } from "./scenes/outro.js";

export const initApp = () => {
  const sound = createSound();
  const state = { hostname: "example.com" };
  initSoundButton(sound);
  initProgress();
  const onHostChange = initDns({ sound, state });
  initUrl({ sound, state, onHostChange });
  initHandshake({ sound });
  initHttp({ sound });
  initDom({ sound });
  initScripts({ sound });
  initLayout({ sound });
  initPaint({ sound });
  initLayers({ sound });
  initRaster({ sound });
  initV8({ sound });
  initGarbageCollection({ sound });
  initProcesses({ sound });
  initOutro({ sound });
};
